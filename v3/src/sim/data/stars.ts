export const STAR_TYPE_MAP: Record<string, StarType> = Object.fromEntries(
  STAR_TYPES.map((s) => [s.id, s]),
);

export function starType(id: string): StarType {
  const t = STAR_TYPE_MAP[id];
  if (!t) throw new Error(`Unknown star type ${id}`);
  return t;
}
