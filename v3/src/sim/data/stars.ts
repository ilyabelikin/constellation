// Star catalogue. Values are loosely realistic; the `solar` multiplier drives
// solar-array / Dyson output, and special stars feed research & exotics.

export interface StarType {
  id: string;
  name: string;
  spectral: string;
  weight: number;
  temperature: number; // Kelvin, drives shader colour
  color: string; // representative sRGB colour
  radius: [number, number]; // solar radii (visual is compressed)
  luminosity: [number, number]; // relative to Sol
  mass: [number, number];
  planets: [number, number];
  /** Multiplier for solar collectors and Dyson swarms. */
  solar: number;
  research: number;
  exotics: number;
  canBeCompanion: boolean;
  description: string;
  special?: "neutron" | "blackhole" | "protostar" | "whitedwarf" | "giant";
}

